// Bundles src/ into a single ExtendScript file: dist/EDL_AE.jsx
//
//   node scripts/build.mjs
//
// The bundle runs as a ScriptUI panel (Window menu), as a plain script
// (File > Scripts > Run Script File) and embedded in the EdlAE.aex plugin.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export const CORE = [
    "src/core/util.jsx",
    "src/core/timecode.jsx",
    "src/core/xml.jsx",
    "src/core/json.jsx",
    "src/core/model.jsx",
    "src/core/fmt_edl.jsx",
    "src/core/fmt_xmeml.jsx",
    "src/core/fmt_fcpxml.jsx",
    "src/core/fmt_otio.jsx",
    "src/core/fmt_csv.jsx",
    "src/core/formats.jsx",
];

export const AE = [
    "src/ae/ae_util.jsx",
    "src/ae/ae_export.jsx",
    "src/ae/ae_import.jsx",
    "src/ae/ae_ui.jsx",
];

export function version() {
    return JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8")).version;
}

// ExtendScript and AEGP_ExecuteScript are happiest with pure ASCII.
function asciiOnly(src) {
    return src.replace(/[^\x00-\x7f]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0"));
}

export function bundle() {
    const parts = [
        `// EDL_AE.jsx ${version()} - EDL / FCP 7 XML / FCPXML / OTIO import and export for After Effects.`,
        "// Generated by scripts/build.mjs from src/. Edit the sources, not this file.",
        "//",
        "// Install: copy to <After Effects>/Support Files/Scripts/ScriptUI Panels/ and open it",
        "// from the Window menu, or run it via File > Scripts > Run Script File.",
        "",
        "(function (thisObj) {",
        `var EDLAE = { version: "${version()}" };`,
        "",
    ];
    for (const rel of [...CORE, ...AE]) {
        const src = fs.readFileSync(path.join(ROOT, rel), "utf8").replace(/\r\n/g, "\n").trimEnd();
        parts.push(`// ---- ${rel} ----`, src, "");
    }
    parts.push("EDLAE.main(thisObj);", "}(this));", "");
    return asciiOnly(parts.join("\n"));
}

// Same code without the UI entry point: exposes $.global.EDLAE_LIB for tests/ae.
export function bundleLib() {
    const b = bundle();
    const tail = "EDLAE.main(thisObj);\n}(this));\n";
    if (!b.endsWith(tail)) { throw new Error("unexpected bundle tail"); }
    return b.slice(0, -tail.length) + "$.global.EDLAE_LIB = EDLAE;\n}(this));\n";
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
    const out = path.join(ROOT, "dist", "EDL_AE.jsx");
    fs.mkdirSync(path.dirname(out), { recursive: true });
    const text = bundle();
    fs.writeFileSync(out, text);
    console.log(`wrote ${path.relative(ROOT, out)} (${(text.length / 1024).toFixed(1)} KB)`);
    const lib = path.join(ROOT, "build", "EDL_AE_lib.jsx");
    fs.mkdirSync(path.dirname(lib), { recursive: true });
    fs.writeFileSync(lib, bundleLib());
}
